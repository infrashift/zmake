//! The built-in variables and implicit rules of GNU Make 4.3, generated from
//! `make -p -f /dev/null`. zmake leaves out the RCS, SCCS and archive member
//! rules. Each rule comes from a suffix rule in GNU Make, so it is active only
//! while `.SUFFIXES` has both of its suffixes (ADR-0018).

/// A built-in variable: name and recursive value.
pub const Variable = struct { name: []const u8, value: []const u8 };

/// A built-in pattern rule. `target` is `%` or `%` plus a suffix.
pub const Rule = struct { target: []const u8, source: []const u8, recipe: []const u8 };

